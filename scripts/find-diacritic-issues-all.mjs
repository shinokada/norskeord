#!/usr/bin/env node
/**
 * find-diacritic-issues-all.mjs
 *
 * Merged replacement for find-diacritic-issues.mjs (Norwegian) and
 * find-diacritic-issues-de-es.mjs (German/Spanish) — same detection logic,
 * driven by a single LANGUAGES config so all three languages share one CLI,
 * one processFile(), and one report writer instead of two near-identical
 * copies of each. Built on top of the generic checkLanguage() helper in
 * scripts/lib/diacritics.mjs, which both original scripts already had
 * available but weren't calling.
 *
 * NEW: --dir flag. Both original scripts only ever looked at
 * draft/{level}/{kind}-{level}-new.json. This script can also point at the
 * production data files in src/lib/data, which use a flat, differently-named
 * layout:
 *
 *   --dir draft  (default)  draft/{level}/vocab-{level}-new.json
 *                           draft/{level}/uttrykk-{level}-new.json
 *
 *   --dir prod              src/lib/data/vocab-{level}.json
 *                           src/lib/data/uttrykk-{level}.json
 *                           (no per-level subfolder, no "-new" suffix)
 *
 * src/lib/data is live production data the app reads from. --fix and
 * --remove still back up to {file}.bak first (same as draft mode), but
 * because these files aren't a scratch draft, treat --dir prod --fix as a
 * real production edit: run without --fix first to see the report, and
 * commit/deploy deliberately afterward.
 *
 * Usage:
 *   node scripts/find-diacritic-issues-all.mjs a2
 *   node scripts/find-diacritic-issues-all.mjs a2 --type vocab
 *   node scripts/find-diacritic-issues-all.mjs a2 --type uttrykk
 *   node scripts/find-diacritic-issues-all.mjs a2 --lang norwegian
 *   node scripts/find-diacritic-issues-all.mjs a2 --lang german
 *   node scripts/find-diacritic-issues-all.mjs a2 --lang spanish
 *   node scripts/find-diacritic-issues-all.mjs a2 --dir prod
 *   node scripts/find-diacritic-issues-all.mjs a2 --dir prod --fix
 *   node scripts/find-diacritic-issues-all.mjs a2 --fix
 *   node scripts/find-diacritic-issues-all.mjs a2 --remove
 *
 * Options:
 *   --type vocab|uttrykk|both              Which file(s) to check (default: both)
 *   --lang norwegian|german|spanish|all    Which language(s) to check (default: all)
 *   --dir draft|prod                       Which data layout to read/write (default: draft)
 *   --fix     Correct flagged tokens in place (backed up to {file}.bak first).
 *   --remove  Remove flagged entries from the file (backed up to {file}.bak
 *             first) so they can be regenerated by the relevant enrichment
 *             script (enrich-vocab.mjs for Norwegian content,
 *             add-language-translations.mjs for German/Spanish translations).
 *
 * Output:
 *   Console: live list of flagged entries, tagged with which language(s) flagged them
 *   File:    scripts/outputs/diacritic-issues-all-{level}-{dir}-{timestamp}.txt
 */

import { readFileSync, writeFileSync, existsSync, copyFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import {
  NO_COMMON_WORD_MAP,
  NO_AMBIGUOUS_WORDS,
  degradeNO,
  bareWordNO,
  DE_COMMON_WORD_MAP,
  DE_AMBIGUOUS_WORDS,
  degradeDE,
  ES_COMMON_WORD_MAP,
  ES_AMBIGUOUS_WORDS,
  degradeES,
  bareWordIntl,
  checkLanguage,
  applyFixes,
  findSpanishPunctuationIssues,
  fixSpanishPunctuation,
  findGermanBigramIssues,
  fixGermanBigrams
} from './lib/diacritics.mjs';

// Words that DE_BIGRAM_RULES (in diacritics.mjs) can resolve unambiguously
// in specific collocations — used below to suppress the redundant
// bare-word ambiguous flag once the bigram check has already turned that
// same occurrence into a fixable issue.
const DE_BIGRAM_RESOLVED_WORDS = new Set(['fuhren', 'ware']);

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(__dirname, '..');
const DRAFT_DIR = join(PROJECT_ROOT, 'draft');
const PROD_DIR = join(PROJECT_ROOT, 'src/lib/data');
const OUTPUT_DIR = join(__dirname, 'outputs');

// ── CLI args ────────────────────────────────────────────────────────────

const rawArgs = process.argv.slice(2);
const REMOVE = rawArgs.includes('--remove');
const FIX = rawArgs.includes('--fix');

function argAfter(flag) {
  const i = rawArgs.indexOf(flag);
  return i !== -1 ? rawArgs[i + 1] : null;
}

const TYPE = argAfter('--type') || 'both';
const LANG = argAfter('--lang') || 'all';
const DIR = argAfter('--dir') || 'draft';

const VALUE_FLAGS = ['--type', '--lang', '--dir'];
const level = rawArgs.find((a, i) => !a.startsWith('--') && !VALUE_FLAGS.includes(rawArgs[i - 1]));

if (!['vocab', 'uttrykk', 'both'].includes(TYPE)) {
  console.error(`❌  Unknown --type "${TYPE}" — must be "vocab", "uttrykk", or "both"`);
  process.exit(1);
}
if (!['norwegian', 'german', 'spanish', 'all'].includes(LANG)) {
  console.error(
    `❌  Unknown --lang "${LANG}" — must be "norwegian", "german", "spanish", or "all"`
  );
  process.exit(1);
}
if (!['draft', 'prod'].includes(DIR)) {
  console.error(`❌  Unknown --dir "${DIR}" — must be "draft" or "prod"`);
  process.exit(1);
}
if (FIX && REMOVE) {
  console.error('❌  --fix and --remove are mutually exclusive — pick one.');
  process.exit(1);
}
if (!level) {
  console.error('❌  Level is required. Example:');
  console.error('    node scripts/find-diacritic-issues-all.mjs a2');
  process.exit(1);
}

// ── Language configs ──────────────────────────────────────────────────────
//
// headwordFields: field(s) holding this language's own word for the entry.
//   Norwegian has two (norsk, lemma) since either can independently show up
//   degraded in the example; German/Spanish each have one (the translation
//   field itself).
// commonFields: fields scanned for degraded closed-class/common words,
//   independent of the headword check.
// fixFields: fields --fix is allowed to rewrite. Deliberately excludes the
//   headword fields themselves (norsk/lemma/german/spanish) for Norwegian's
//   case, matching the original script's behavior of treating the headword
//   as ground truth and only patching text derived from it — but German/
//   Spanish's own translation field is corrected too, matching the
//   original de-es script.

const LANGUAGES = {
  norwegian: {
    label: 'Norwegian',
    headwordFields: ['norsk', 'lemma'],
    commonFields: ['norsk', 'lemma', 'example', 'definition'],
    fixFields: ['example', 'definition'],
    exampleField: 'example',
    specialChars: /[æøåÆØÅ]/,
    degrade: degradeNO,
    bareWord: bareWordNO,
    wordMap: NO_COMMON_WORD_MAP,
    ambiguousWords: NO_AMBIGUOUS_WORDS,
    punctuation: false
  },
  german: {
    label: 'German',
    headwordFields: ['german'],
    commonFields: ['german', 'example_german'],
    fixFields: ['german', 'example_german'],
    exampleField: 'example_german',
    specialChars: /[üöäßÜÖÄ]/,
    degrade: degradeDE,
    bareWord: bareWordIntl,
    wordMap: DE_COMMON_WORD_MAP,
    ambiguousWords: DE_AMBIGUOUS_WORDS,
    punctuation: false,
    bigram: true
  },
  spanish: {
    label: 'Spanish',
    headwordFields: ['spanish'],
    commonFields: ['spanish', 'example_spanish'],
    fixFields: ['spanish', 'example_spanish'],
    exampleField: 'example_spanish',
    specialChars: /[áéíóúñÁÉÍÓÚÑ¿¡]/,
    degrade: degradeES,
    bareWord: bareWordIntl,
    wordMap: ES_COMMON_WORD_MAP,
    ambiguousWords: ES_AMBIGUOUS_WORDS,
    punctuation: true
  }
};

const activeLangs = LANG === 'all' ? ['norwegian', 'german', 'spanish'] : [LANG];

// ── Per-entry, per-language issue detection ────────────────────────────────

function findIssuesForLang(entry, langKey) {
  const cfg = LANGUAGES[langKey];
  let issues = [];
  let ambiguous = [];
  let headwordFixes = [];

  const exampleValue = entry[cfg.exampleField];

  // 1. Headword check — run once per headword field (Norwegian has two:
  // norsk and lemma; German/Spanish have one), each independently compared
  // against the same example field. fields:[] here so the common-word scan
  // below isn't duplicated once per headword field.
  for (const hwField of cfg.headwordFields) {
    const result = checkLanguage({
      headword: entry[hwField],
      fields: [],
      specialChars: cfg.specialChars,
      degrade: cfg.degrade,
      bareWord: cfg.bareWord,
      wordMap: cfg.wordMap,
      ambiguousWords: cfg.ambiguousWords,
      exampleField: cfg.exampleField,
      exampleValue
    });
    issues = issues.concat(result.issues.map((i) => ({ ...i, lang: langKey })));
    headwordFixes = headwordFixes.concat(result.headwordFixes);
  }

  // 2. Common-word check — across this language's commonFields, run once
  // (headword:'' and exampleValue:'' so this call can't re-trigger the
  // headword check already done above).
  const commonResult = checkLanguage({
    headword: '',
    fields: cfg.commonFields.map((name) => ({ name, value: entry[name] })),
    specialChars: cfg.specialChars,
    degrade: cfg.degrade,
    bareWord: cfg.bareWord,
    wordMap: cfg.wordMap,
    ambiguousWords: cfg.ambiguousWords,
    exampleField: cfg.exampleField,
    exampleValue: ''
  });
  issues = issues.concat(commonResult.issues.map((i) => ({ ...i, lang: langKey })));
  let commonAmbiguous = commonResult.ambiguous;

  // 3. Punctuation check (Spanish only)
  if (cfg.punctuation) {
    issues.push(
      ...findSpanishPunctuationIssues(exampleValue, cfg.exampleField).map((i) => ({
        ...i,
        lang: langKey
      }))
    );
  }

  // 4. Bigram disambiguation (German only) — some otherwise-ambiguous
  // words (see DE_AMBIGUOUS_WORDS) are unambiguous in specific fixed
  // collocations (see DE_BIGRAM_RULES in diacritics.mjs). Run it per field,
  // promote any match to a fixable issue, and drop the now-redundant
  // ambiguous flag for that same field so the same occurrence isn't
  // reported twice (once as fixable, once as "needs manual review").
  if (cfg.bigram) {
    const bigramFlaggedFields = new Set();
    for (const field of cfg.commonFields) {
      const bigramIssues = findGermanBigramIssues(entry[field], field);
      if (bigramIssues.length > 0) {
        bigramFlaggedFields.add(field);
        issues = issues.concat(bigramIssues.map((i) => ({ ...i, lang: langKey })));
      }
    }
    if (bigramFlaggedFields.size > 0) {
      commonAmbiguous = commonAmbiguous.filter(
        (a) =>
          !(
            bigramFlaggedFields.has(a.field) &&
            DE_BIGRAM_RESOLVED_WORDS.has((a.detail.match(/contains "([a-zA-Z]+)"/) || [])[1])
          )
      );
    }
  }
  ambiguous = ambiguous.concat(commonAmbiguous.map((a) => ({ ...a, lang: langKey })));

  return { issues, ambiguous, headwordFixes };
}

function findIssues(entry) {
  let issues = [];
  let ambiguous = [];
  const headwordFixesByLang = {};

  for (const langKey of activeLangs) {
    const result = findIssuesForLang(entry, langKey);
    issues = issues.concat(result.issues);
    ambiguous = ambiguous.concat(result.ambiguous);
    if (result.headwordFixes.length > 0) headwordFixesByLang[langKey] = result.headwordFixes;
  }

  return { issues, ambiguous, headwordFixesByLang };
}

// ── File path resolution ────────────────────────────────────────────────

// Only the example field(s) belonging to language(s) that actually flagged
// this entry — e.g. if only Spanish flagged an issue, show example_spanish
// only, not example/example_german too.
function relevantExampleLines(entry, entryIssues, indent) {
  const flaggedLangs = new Set(entryIssues.map((i) => i.lang));
  const lines = [];
  const shownFields = new Set();

  // Always show the Norwegian example first (if present) as a reference
  // point for comparison, even when Norwegian itself isn't what flagged
  // this entry.
  if (entry.example) {
    lines.push(`${indent}example: "${entry.example}"`);
    shownFields.add('example');
  }

  for (const langKey of activeLangs) {
    if (!flaggedLangs.has(langKey)) continue;
    const field = LANGUAGES[langKey].exampleField;
    if (shownFields.has(field)) continue;
    if (entry[field]) {
      lines.push(`${indent}${field}: "${entry[field]}"`);
      shownFields.add(field);
    }
  }
  return lines;
}

function buildFilePath(kind, level) {
  if (DIR === 'prod') {
    return { filename: `${kind}-${level}.json`, filePath: join(PROD_DIR, `${kind}-${level}.json`) };
  }
  const draftDir = join(DRAFT_DIR, level);
  return {
    filename: `${kind}-${level}-new.json`,
    filePath: join(draftDir, `${kind}-${level}-new.json`)
  };
}

// ── Process one file ──────────────────────────────────────────────────────

function processFile(kind, level) {
  const { filename, filePath } = buildFilePath(kind, level);

  if (!existsSync(filePath)) {
    console.log(`  ⏭️   ${filename} not found — skipping`);
    return { filename, flagged: [], ambiguousFlagged: [] };
  }

  const entries = JSON.parse(readFileSync(filePath, 'utf8'));
  const flagged = [];
  const ambiguousFlagged = [];

  for (const entry of entries) {
    const { issues, ambiguous, headwordFixesByLang } = findIssues(entry);
    if (issues.length > 0) flagged.push({ entry, issues, headwordFixesByLang });
    if (ambiguous.length > 0) ambiguousFlagged.push({ entry, ambiguous });
  }

  console.log(`\n${'─'.repeat(60)}`);
  console.log(`📄  ${filename}  (${entries.length} entries)`);
  console.log(`${'─'.repeat(60)}`);

  for (const { entry, issues } of flagged) {
    console.log(`  ⚠️   [${entry.id || entry.lemma}] norsk: "${entry.norsk}"`);
    for (const line of relevantExampleLines(entry, issues, '       ')) console.log(line);
    for (const issue of issues) {
      console.log(`       - [${issue.lang}] ${issue.detail}`);
    }
  }

  console.log(`\n  → ${flagged.length} / ${entries.length} entries auto-detected (fixable)`);

  if (ambiguousFlagged.length > 0) {
    console.log(
      `\n  🟡  ${ambiguousFlagged.length} entries need MANUAL review (ambiguous, not auto-fixed):`
    );
    for (const { entry, ambiguous } of ambiguousFlagged) {
      console.log(`     [${entry.id || entry.lemma}] norsk: "${entry.norsk}"`);
      for (const line of relevantExampleLines(entry, ambiguous, '       ')) console.log(line);
      for (const a of ambiguous) console.log(`       - [${a.lang}] ${a.detail}`);
    }
  }

  if (FIX && flagged.length > 0) {
    const bakPath = `${filePath}.bak`;
    copyFileSync(filePath, bakPath);

    for (const { entry, headwordFixesByLang } of flagged) {
      for (const langKey of activeLangs) {
        const cfg = LANGUAGES[langKey];
        const hfs = headwordFixesByLang[langKey] || [];
        for (const field of cfg.fixFields) {
          if (entry[field]) {
            let value = entry[field];
            if (cfg.bigram) value = fixGermanBigrams(value);
            entry[field] = applyFixes(value, hfs, cfg.wordMap);
          }
        }
        if (cfg.punctuation && entry[cfg.exampleField]) {
          entry[cfg.exampleField] = fixSpanishPunctuation(entry[cfg.exampleField]);
        }
      }
    }

    writeFileSync(filePath, JSON.stringify(entries, null, 2) + '\n', 'utf8');
    console.log(`  💾  Backed up to ${bakPath.replace(PROJECT_ROOT, '.')}`);
    console.log(`  ✅  Fixed ${flagged.length} entries in place in ${filename}`);
  } else if (FIX) {
    console.log(`  (nothing to fix)`);
  }

  if (REMOVE && flagged.length > 0) {
    const flaggedLemmas = new Set(flagged.map(({ entry }) => entry.lemma));
    const remaining = entries.filter((e) => !flaggedLemmas.has(e.lemma));

    const bakPath = `${filePath}.bak`;
    copyFileSync(filePath, bakPath);
    writeFileSync(filePath, JSON.stringify(remaining, null, 2) + '\n', 'utf8');

    console.log(`  💾  Backed up to ${bakPath.replace(PROJECT_ROOT, '.')}`);
    console.log(
      `  🗑️   Removed ${flagged.length} flagged entries — ${remaining.length} remain in ${filename}`
    );
    console.log(
      `  ↻  Re-run enrich-vocab.mjs (Norwegian content) and/or` +
        ` add-language-translations.mjs (German/Spanish) for this level to` +
        ` regenerate the removed entries.`
    );
  } else if (REMOVE) {
    console.log(`  (nothing to remove)`);
  }

  return { filename, flagged, ambiguousFlagged };
}

// ── Report ──────────────────────────────────────────────────────────────

function writeReport(level, results) {
  mkdirSync(OUTPUT_DIR, { recursive: true });
  const ts = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const outPath = join(OUTPUT_DIR, `diacritic-issues-all-${level}-${DIR}-${ts}.txt`);

  const lines = [];
  lines.push(`Diacritic issue scan (all languages): ${level}`);
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`Dir: ${DIR}`);
  lines.push(`Languages: ${activeLangs.join(', ')}`);
  lines.push(
    `Mode: ${
      FIX
        ? 'FIX (flagged tokens corrected in place)'
        : REMOVE
          ? 'REMOVE (flagged entries stripped from file)'
          : 'REPORT ONLY'
    }`
  );
  lines.push('');

  for (const { filename, flagged, ambiguousFlagged } of results) {
    lines.push(`=== ${filename} ===`);
    lines.push(`Auto-detected (fixable): ${flagged.length}`);
    lines.push(`Needs manual review (ambiguous): ${ambiguousFlagged.length}`);
    lines.push('');
    for (const { entry, issues } of flagged) {
      lines.push(`[${entry.id || entry.lemma}] norsk: "${entry.norsk}"`);
      lines.push(...relevantExampleLines(entry, issues, '  '));
      for (const issue of issues) lines.push(`  - [${issue.lang}] ${issue.detail}`);
      lines.push('');
    }
    if (ambiguousFlagged.length > 0) {
      lines.push(`--- Manual review needed ---`);
      for (const { entry, ambiguous } of ambiguousFlagged) {
        lines.push(`[${entry.id || entry.lemma}] norsk: "${entry.norsk}"`);
        lines.push(...relevantExampleLines(entry, ambiguous, '  '));
        for (const a of ambiguous) lines.push(`  - [${a.lang}] ${a.detail}`);
        lines.push('');
      }
    }
  }

  writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
  console.log(`\n📝  Full report written to: ${outPath.replace(PROJECT_ROOT, '.')}`);
}

// ── Main ──────────────────────────────────────────────────────────────────

console.log(`🔍  find-diacritic-issues-all.mjs`);
console.log(`    Level: ${level}`);
console.log(`    Type:  ${TYPE}`);
console.log(`    Lang:  ${LANG}`);
console.log(`    Dir:   ${DIR}${DIR === 'prod' ? '  (⚠️  production data — src/lib/data)' : ''}`);
console.log(
  `    Mode:  ${FIX ? 'FIX flagged tokens in place' : REMOVE ? 'REMOVE flagged entries' : 'report only'}`
);

const results = [];

if (TYPE === 'vocab' || TYPE === 'both') {
  results.push(processFile('vocab', level));
}
if (TYPE === 'uttrykk' || TYPE === 'both') {
  results.push(processFile('uttrykk', level));
}

writeReport(level, results);

const totalFlagged = results.reduce((s, r) => s + r.flagged.length, 0);
console.log(`\n${'═'.repeat(60)}`);
console.log(`📊  Total flagged across ${results.length} file(s): ${totalFlagged}`);
